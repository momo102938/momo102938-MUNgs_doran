export function jobLines(job: string): Line[] {
  return occupations.find((o) => o.match.test(job))?.lines || scenes.office;
}
export function usesPolite(a: Character, b: Character) {
  return (a.politeToOlder && b.age > a.age) || /존댓말|정중/.test(a.tone);
}
export function sceneLines(
  placeId: string,
  action: Action,
  a: Character,
  b: Character,
  rel?: Relationship,
): string[] {
  const polite = usesPolite(a, b),
    list: Line[] = [
      ...(placeId === "office"
        ? [
            ...jobLines(a.job),
            ["점심 같이 먹을래?", "점심 같이 드실래요?"] as Line,
            ["잠깐 쉬었다 하자.", "잠깐 쉬었다 해요."] as Line,
          ]
        : scenes[placeId] || scenes.home),
    ];
  if ((placeId === "school" || placeId === "university") && isTeacher(a.job)) {
    list.splice(
      0,
      list.length,
      ...(isTeacher(b.job)
        ? jobLines(a.job)
        : ([
            ["이 문제 어디까지 풀었어?", "이 문제 어디까지 풀었어요?"],
            [
              "모르는 부분 있으면 물어봐. 같이 보자.",
              "모르는 부분 있으면 물어봐요. 같이 봐요.",
            ],
            [
              "오늘 수업은 여기까지야. 수고했어.",
              "오늘 수업은 여기까지예요. 수고했어요.",
            ],
            [
              "과제는 다음 시간까지 내면 돼.",
              "과제는 다음 시간까지 내면 돼요.",
            ],
          ] as Line[])),
    );
  }
  if (action === "식사") {
    for (let i = list.length - 1; i >= 0; i--)
      if (/저녁 뭐|점심 같이|뭐 먹|식사 준비/.test(list[i][0]))
        list.splice(i, 1);
  }
  if (action === "식사")
    list.push(
      ["이거 맛있다. 너도 먹어 봐.", "이거 맛있어요. 한번 드셔 보세요."],
      [
        "반찬 더 줄까? 아직 많이 남았어.",
        "반찬 더 드릴까요? 아직 많이 남았어요.",
      ],
      ["잘 먹었다. 설거지는 내가 할게.", "잘 먹었어요. 설거지는 제가 할게요."],
    );
  if (a.fatigue > 65)
    list.push([
      "아, 졸려. 잠깐만 쉬었다 하자.",
      "좀 졸리네요. 잠깐만 쉬었다 해요.",
    ]);
  if (a.mood < 35)
    list.push([
      "오늘 좀 기운이 없네. 옆에 있어 줘.",
      "오늘 좀 기운이 없네요. 옆에 있어 주실래요?",
    ]);
  if (rel && rel.intimacy < 35)
    list.push([
      "아까 말 좀 세게 했지. 미안해.",
      "아까 말이 좀 심했죠. 미안해요.",
    ]);
  if (rel?.type === "연인" && a.age >= 18 && b.age >= 18)
    list.push(
      [
        "손 좀 줘. 그냥 잡고 있고 싶어서.",
        "손 좀 줘요. 그냥 잡고 있고 싶어서요.",
      ],
      ["오늘은 좀 더 같이 있자.", "오늘은 좀 더 같이 있어요."],
    );
  if (rel?.type === "부모와 자녀" && a.age > b.age)
    list.push([
      "오늘 학교 어땠어? 재밌는 일 없었고?",
      "오늘 학교 어땠어요? 재밌는 일 있었어요?",
    ]);
  if (/밝|활발|외향/.test(a.personality))
    list.push([
      "있잖아, 오늘 웃긴 일 있었는데 들어 볼래?",
      "있잖아요, 오늘 웃긴 일 있었는데 들어 보실래요?",
    ]);
  if (/조용|수줍|내향/.test(a.personality))
    list.push(["나 그냥 옆에 있어도 돼?", "저 그냥 옆에 있어도 돼요?"]);
  return list.map((l) => l[polite ? 1 : 0]);
}
