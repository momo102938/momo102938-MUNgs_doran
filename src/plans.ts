const id = () => crypto.getRandomValues(new Uint32Array(3)).join("-");
const f = (
  kind: FurnitureKind,
  x: number,
  y: number,
  w = FURNITURE_META[kind].w,
  h = FURNITURE_META[kind].h,
  rotation = 0,
  label: string = kind,
  color = "",
): Furniture => ({ id: id(), kind, x, y, w, h, rotation, label, color });
const room = (
  name: string,
  x: number,
  y: number,
  w: number,
  h: number,
  color = "#eee2c8",
  pattern: Room["pattern"] = "wood",
  radius = 0,
): Room => ({
  id: id(),
  name,
  x,
  y,
  w,
  h,
  color,
  pattern,
  border: false,
  radius,
});
